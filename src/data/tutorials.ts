function lesson(
  input: Omit<Tutorial, "start"> & { electrical?: boolean; gas?: boolean },
): Tutorial {
  const { electrical, gas, ...data } = input;
  const part = data.chapters[0].part;
  return {
    ...data,
    start: "safety",
    nodes: {
      safety: q(
        "先確認現場安全",
        gas
          ? "從安全距離觀察；不要為了測試反覆點火。"
          : electrical
            ? "保持手部與地面乾燥，只看設備外觀，不拆蓋、不觸碰配線。"
            : "先看周圍是否乾燥，確認水沒有接近插座或電器。",
        part,
        gas
          ? "有瓦斯味、焦味，或使用時感到頭暈不適嗎？"
          : electrical
            ? "有焦味、煙霧、火花、異常熱感或潮濕嗎？"
            : "有大量湧水、污水回流，或漏水接近電器嗎？",
        "danger",
        "observe",
      ),
      danger: r(
        "停止檢查，先確保安全",
        gas
          ? "這些徵兆需要立即停止使用，不能靠畫面判斷設備是否安全。"
          : electrical
            ? "可能有觸電或起火風險，請停止使用該設備。"
            : "先避免接觸污水或帶電設備，再處理漏水。",
        part,
        gas
          ? [
              "離開現場到通風處，不開關電器、不點火。",
              "在安全處聯絡瓦斯供應商；疑似外洩或身體不適請打 119。",
              "經專業人員確認前，不再使用熱水器。",
            ]
          : electrical
            ? [
                "不要觸碰異常插座、開關或配電箱。",
                "請合格電工檢查；如有煙霧或起火，撤離並打 119。",
                "不要反覆送電測試。",
              ]
            : [
                "若供水閥安全可及，關閉供水；不要走進有電器的積水區。",
                "停止使用受影響設備，聯絡水電師傅或管理單位。",
                "有起火、觸電或人身危險時，移至安全處並打 119。",
              ],
        "danger",
      ),
      unsure: r(
        "保留觀察，交給專業確認",
        "無法確認的項目不需要猜。把目前看到的現象交給師傅，能更快說明問題。",
        part,
        [
          "停止進一步拆卸或測試。",
          "記下發生時間、位置與設備型號。",
          "下載這份檢查摘要，聯絡原廠或合格水電人員。",
        ],
      ),
      ...data.nodes,
    },
  };
}

