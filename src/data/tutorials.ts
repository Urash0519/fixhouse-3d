export function nextNode(
  tutorial: Tutorial,
  nodeId: string,
  answer: "yes" | "no" | "unsure",
): string {
  const node = tutorial.nodes[nodeId];
  if (!node || node.kind !== "question") return nodeId;
  return answer === "unsure" ? "unsure" : node[answer];
}
